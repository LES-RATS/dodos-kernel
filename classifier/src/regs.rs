//! The register definitions for Rust and for Zig (D-126: the Rust build
//! prints the constants of the Zig layer as a Zig file).
//!
//! Only registers the kernel may touch are defined: class `kernel`, and
//! class `gate`, marked `gate_only`. Fields are those with one contiguous
//! range in every layout of the register.

use std::fmt::Write as _;

use crate::{Class, Classification, Reg, RegEncoding, Spec};

fn ident(name: &str) -> String {
    let s: String = name
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_uppercase()
            } else {
                '_'
            }
        })
        .collect();
    if s.starts_with(|c: char| c.is_ascii_digit()) {
        format!("F{s}")
    } else {
        s
    }
}

fn selected<'s>(spec: &'s Spec, classes: &Classification) -> Vec<(&'s Reg, bool)> {
    let mut out: Vec<(&Reg, bool)> = spec
        .regs
        .iter()
        .filter_map(|r| match classes.class_of(&r.key) {
            Some(Class::Kernel) => Some((r, false)),
            Some(Class::Gate) => Some((r, true)),
            _ => None,
        })
        .collect();
    out.sort_by(|a, b| a.0.name.cmp(&b.0.name));
    out.dedup_by(|a, b| ident(&a.0.name) == ident(&b.0.name));
    out
}

/// Fields with distinct identifiers, in order of their bits.
fn fields(r: &Reg) -> Vec<(String, u8, u8)> {
    let mut out: Vec<(String, u8, u8)> = Vec::new();
    for f in &r.fields {
        let id = ident(&f.name);
        if !out.iter().any(|(n, _, _)| *n == id) {
            out.push((id, f.lsb, f.width));
        }
    }
    out.sort_by_key(|(_, lsb, _)| *lsb);
    out
}

fn header(spec: &Spec, comment: &str) -> String {
    format!(
        "{c} Generated by dodos-classifier from {}. Do not edit.\n{c} {}\n\n",
        spec.release,
        spec.notice,
        c = comment
    )
}

pub fn rust(spec: &Spec, classes: &Classification) -> String {
    let mut out = header(spec, "//");
    out.push_str(
        "/// A bit field of a register.\n#[derive(Debug, Clone, Copy, PartialEq, Eq)]\n\
         pub struct Field {\n    pub lsb: u8,\n    pub width: u8,\n}\n\n",
    );
    match spec.arch {
        crate::Arch::Riscv64 => out.push_str(
            "/// A CSR: its address; `gate_only` if only the gate may write it.\n\
             #[derive(Debug, Clone, Copy, PartialEq, Eq)]\npub struct Csr {\n    pub address: u16,\n    pub gate_only: bool,\n}\n\n",
        ),
        _ => out.push_str(
            "/// A system register: the operands of `MRS` and `MSR`; `gate_only` if\n\
             /// only the gate may write it.\n#[derive(Debug, Clone, Copy, PartialEq, Eq)]\n\
             pub struct SysReg {\n    pub op0: u8,\n    pub op1: u8,\n    pub crn: u8,\n    pub crm: u8,\n    pub op2: u8,\n    pub gate_only: bool,\n}\n\n",
        ),
    }
    for (r, gate) in selected(spec, classes) {
        let id = ident(&r.name);
        let _ = match &r.encoding {
            RegEncoding::Sys {
                op0,
                op1,
                crn,
                crm,
                op2,
            } => writeln!(
                out,
                "pub const {id}: SysReg = SysReg {{ op0: {op0}, op1: {op1}, crn: {crn}, crm: {crm}, op2: {op2}, gate_only: {gate} }};"
            ),
            RegEncoding::Csr(a) => writeln!(
                out,
                "pub const {id}: Csr = Csr {{ address: {a:#05x}, gate_only: {gate} }};"
            ),
        };
        let fs = fields(r);
        if !fs.is_empty() {
            let _ = writeln!(
                out,
                "pub mod {} {{\n    use super::Field;",
                id.to_ascii_lowercase()
            );
            for (name, lsb, width) in fs {
                let _ = writeln!(
                    out,
                    "    pub const {name}: Field = Field {{ lsb: {lsb}, width: {width} }};"
                );
            }
            out.push_str("}\n");
        }
    }
    out
}

pub fn zig(spec: &Spec, classes: &Classification) -> String {
    let mut out = header(spec, "//");
    out.push_str(
        "/// A bit field of a register.\npub const Field = struct { lsb: u8, width: u8 };\n",
    );
    match spec.arch {
        crate::Arch::Riscv64 => out.push_str(
            "/// A CSR: its address; `gate_only` if only the gate may write it.\n\
             pub const Csr = struct { address: u12, gate_only: bool };\n\n",
        ),
        _ => out.push_str(
            "/// A system register: the operands of `MRS` and `MSR`; `gate_only` if\n\
             /// only the gate may write it.\n\
             pub const SysReg = struct { op0: u2, op1: u3, crn: u4, crm: u4, op2: u3, gate_only: bool };\n\n",
        ),
    }
    for (r, gate) in selected(spec, classes) {
        let id = ident(&r.name);
        let _ = match &r.encoding {
            RegEncoding::Sys {
                op0,
                op1,
                crn,
                crm,
                op2,
            } => writeln!(
                out,
                "pub const {id} = SysReg{{ .op0 = {op0}, .op1 = {op1}, .crn = {crn}, .crm = {crm}, .op2 = {op2}, .gate_only = {gate} }};"
            ),
            RegEncoding::Csr(a) => writeln!(
                out,
                "pub const {id} = Csr{{ .address = {a:#05x}, .gate_only = {gate} }};"
            ),
        };
        let fs = fields(r);
        if !fs.is_empty() {
            let _ = writeln!(out, "pub const {id}_fields = struct {{");
            for (name, lsb, width) in fs {
                let _ = writeln!(
                    out,
                    "    pub const {name} = Field{{ .lsb = {lsb}, .width = {width} }};"
                );
            }
            out.push_str("};\n");
        }
    }
    // Every declaration is analysed when the file is compiled alone.
    out.push_str("\ncomptime {\n    for (@typeInfo(@This()).@\"struct\".decl_names) |n| _ = @field(@This(), n);\n}\n");
    out
}
